<?php
ob_start();
ini_set('display_errors', 0);
error_reporting(E_ALL);
require_once __DIR__ . '/../../config/config.php';
require_once __DIR__ . '/../../includes/auth.php';
ob_clean();
header('Content-Type: application/json');

$auth = getAuth();
if (!$auth->isLoggedIn() || !$auth->isAdmin()) {
    http_response_code(403);
    echo json_encode(['error' => 'Unauthorized']);
    exit;
}

$db = getDB();
$db->query("CREATE TABLE IF NOT EXISTS site_settings (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_timeout INTEGER DEFAULT 30,
    max_upload_size INTEGER DEFAULT 50,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
)");

if ($_SERVER['REQUEST_METHOD'] === 'GET') {
    $row = $db->fetchOne("SELECT * FROM site_settings ORDER BY id DESC LIMIT 1");
    echo json_encode(['success' => true, 'settings' => $row ?: ['session_timeout' => 30, 'max_upload_size' => 50]]);
    exit;
}

$input = json_decode(file_get_contents('php://input'), true);
if (!is_array($input)) {
    $input = $_POST;
}
$timeout = (int) ($input['session_timeout'] ?? 30);
$upload = (int) ($input['max_upload_size'] ?? 50);
$id = $db->insert(
    "INSERT INTO site_settings (session_timeout, max_upload_size, updated_at) VALUES (?, ?, NOW())",
    [$timeout, $upload]
);
echo json_encode(['success' => true, 'id' => $id, 'message' => 'Settings saved to the database.']);
