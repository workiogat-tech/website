<?php
/**
 * Give Back Content API
 */
// Start output buffering to catch any unexpected output
ob_start();

// Suppress error display for API endpoints (errors will be logged but not displayed)
ini_set('display_errors', 0);
error_reporting(E_ALL);

require_once __DIR__ . '/../../config/config.php';
ini_set('display_errors', '0');

// Clear any output that may have been generated
ob_clean();

// Set JSON header
header('Content-Type: application/json; charset=utf-8');
header('Cache-Control: no-store, no-cache, must-revalidate');

$db = getDB();
$method = $_SERVER['REQUEST_METHOD'];

function givebackEnsureColumns($db): void {
    $db->query(
        "CREATE TABLE IF NOT EXISTS giveback_content (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            title TEXT,
            subtitle TEXT,
            description TEXT,
            hero_image TEXT,
            contact_phone VARCHAR(50),
            contact_email VARCHAR(100),
            payment_details TEXT,
            needs TEXT,
            is_active SMALLINT DEFAULT 1,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        )"
    );
    foreach ([
        'title TEXT',
        'subtitle TEXT',
        'description TEXT',
        'hero_image TEXT',
        'contact_phone VARCHAR(50)',
        'contact_email VARCHAR(100)',
        'payment_details TEXT',
        'needs TEXT',
        'is_active SMALLINT DEFAULT 1',
        'updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP',
    ] as $column) {
        try {
            $db->query("ALTER TABLE giveback_content ADD COLUMN IF NOT EXISTS {$column}");
        } catch (Exception $e) {
            error_log('Giveback column was not added: ' . $e->getMessage());
        }
    }
}

function givebackDecodeField($value, $fallback) {
    if (is_array($value)) {
        return $value;
    }
    if (!is_string($value) || trim($value) === '') {
        return $fallback;
    }
    $decoded = json_decode($value, true);
    return is_array($decoded) ? $decoded : $fallback;
}

if ($method === 'GET') {
    try {
        $content = $db->fetchOne(
            "SELECT * FROM giveback_content WHERE is_active::text IN ('1', 't', 'true') ORDER BY created_at DESC LIMIT 1"
        );
        
        if ($content) {
            $content['payment_details'] = givebackDecodeField($content['payment_details'] ?? null, []);
            $content['needs'] = givebackDecodeField($content['needs'] ?? null, []);
            echo json_encode($content);
        } else {
            echo json_encode(['payment_details' => [], 'needs' => []]);
        }
    } catch (Throwable $e) {
        http_response_code(500);
        echo json_encode(['error' => 'Failed to fetch giveback content: ' . $e->getMessage()]);
    }
    exit;
} elseif ($method === 'POST' || $method === 'PUT') {
    try {
        require_once __DIR__ . '/../../includes/auth.php';
        $auth = getAuth();
        if (!$auth->isLoggedIn() || !$auth->isAdmin()) {
            http_response_code(403);
            echo json_encode(['error' => 'Unauthorized']);
            exit;
        }
        
        // Handle both JSON and form data
        $contentType = $_SERVER['CONTENT_TYPE'] ?? '';
        if (strpos($contentType, 'application/json') !== false) {
            $input = json_decode(file_get_contents('php://input'), true);
        } else {
            $input = $_POST;
        }
        
        if (!is_array($input)) {
            throw new Exception('No data provided');
        }

        givebackEnsureColumns($db);

        $title = trim((string)($input['title'] ?? ''));
        $subtitle = trim((string)($input['subtitle'] ?? ''));
        $description = trim((string)($input['description'] ?? ''));
        $heroImage = trim((string)($input['hero_image'] ?? ''));
        $contactPhone = trim((string)($input['contact_phone'] ?? ''));
        $contactEmail = trim((string)($input['contact_email'] ?? ''));
        
        $jsonFlags = JSON_UNESCAPED_UNICODE | JSON_INVALID_UTF8_SUBSTITUTE;

        // Handle payment_details
        $paymentDetails = '{}';
        if (isset($input['payment_details']) && is_array($input['payment_details'])) {
            $encoded = json_encode($input['payment_details'], $jsonFlags);
            $paymentDetails = $encoded === false ? '{}' : $encoded;
        } elseif (isset($input['payment_details']) && is_string($input['payment_details'])) {
            $paymentDetails = $input['payment_details'];
        }
        
        // Handle needs
        $needs = '[]';
        if (isset($input['needs'])) {
            if (is_array($input['needs'])) {
                $encoded = json_encode($input['needs'], $jsonFlags);
                $needs = $encoded === false ? '[]' : $encoded;
            } elseif (is_string($input['needs'])) {
                $needs = $input['needs'];
            }
        }
        
        // Check if content exists
        $existing = $db->fetchOne(
            "SELECT * FROM giveback_content WHERE is_active::text IN ('1', 't', 'true') ORDER BY created_at DESC LIMIT 1"
        );

        if ($description === '' && is_array($existing) && !empty($existing['description'])) {
            $description = $existing['description'];
        }
        
        $values = [
            $title !== '' ? $title : null,
            $subtitle !== '' ? $subtitle : null,
            $description !== '' ? $description : null,
            $heroImage !== '' ? $heroImage : null,
            $contactPhone !== '' ? $contactPhone : null,
            $contactEmail !== '' ? $contactEmail : null,
            $paymentDetails,
            $needs,
        ];

        if (!empty($existing['id'])) {
            $values[] = $existing['id'];
            $db->update(
                "UPDATE giveback_content SET title = ?, subtitle = ?, description = ?, hero_image = ?, contact_phone = ?, contact_email = ?, payment_details = ?, needs = ?, updated_at = CURRENT_TIMESTAMP WHERE id = ?",
                $values
            );
            $savedId = $existing['id'];
        } else {
            $savedId = $db->insert(
                "INSERT INTO giveback_content (title, subtitle, description, hero_image, contact_phone, contact_email, payment_details, needs, is_active, created_at) VALUES (?, ?, ?, ?, ?, ?, ?, ?, 1, CURRENT_TIMESTAMP)",
                $values
            );
        }

        $payload = json_encode([
            'success' => true,
            'id' => $savedId,
            'message' => 'Give Back content saved successfully'
        ]);
        echo $payload === false ? '{"success":true,"message":"Give Back content saved successfully"}' : $payload;
    } catch (Throwable $e) {
        http_response_code(500);
        error_log("Giveback content save error: " . $e->getMessage());
        $payload = json_encode(['error' => 'Failed to save giveback content: ' . $e->getMessage()]);
        echo $payload === false ? '{"error":"Failed to save giveback content"}' : $payload;
    }
    exit;
} else {
    http_response_code(405);
    echo json_encode(['error' => 'Method not allowed']);
    exit;
}

if (ob_get_level()) {
    ob_end_flush();
}
